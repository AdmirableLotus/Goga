import { beforeEach, expect, it, vi } from 'vitest'
const mock = vi.hoisted(() => ({ invalidate: vi.fn(), audit: vi.fn(), actions: vi.fn(), agent: vi.fn(), mission: vi.fn(), developer: vi.fn(), error: vi.fn() }))
vi.mock('../securityWorkspace', () => ({ SecurityWorkspaceService: { getInstance: () => ({ invalidateApprovals: mock.invalidate, getActive: () => ({ id: 'active' }), logAudit: mock.audit }) } }))
vi.mock('../actionStore', () => ({ ActionStore: { getInstance: () => ({ stopAll: mock.actions }) } }))
vi.mock('../agentLoop', () => ({ AgentLoop: { getInstance: () => ({ stop: mock.agent }) } }))
vi.mock('../missionEngine', () => ({ MissionEngine: { getInstance: () => ({ listMissions: () => [{ id: 'running', status: 'running' }, { id: 'finished', status: 'completed' }], stop: mock.mission }) } }))
vi.mock('../../handlers/developer', () => ({ stopDeveloperTask: mock.developer }))
vi.mock('../logs', () => ({ LogService: { getInstance: () => ({ error: mock.error }) } }))
import { emergencyStop } from '../emergencyStop'
beforeEach(() => { vi.clearAllMocks(); mock.audit.mockReset() })
it('revokes grants and stops every running workflow without restarting completed missions', () => {
  emergencyStop('User stop')
  expect(mock.invalidate).toHaveBeenCalledOnce()
  expect(mock.actions).toHaveBeenCalledOnce()
  expect(mock.agent).toHaveBeenCalledWith('User stop')
  expect(mock.mission).toHaveBeenCalledOnce()
  expect(mock.mission).toHaveBeenCalledWith('running')
  expect(mock.developer).toHaveBeenCalledOnce()
  expect(mock.audit).toHaveBeenCalledOnce()
})
it('audit storage failure does not prevent emergency cancellation', () => {
  mock.audit.mockImplementation(() => { throw new Error('disk unavailable') })
  expect(() => emergencyStop()).not.toThrow()
  expect(mock.agent).toHaveBeenCalledOnce()
  expect(mock.mission).toHaveBeenCalledOnce()
  expect(mock.error).toHaveBeenCalledOnce()
})
